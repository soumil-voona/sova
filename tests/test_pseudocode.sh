# check_pseudocode NAME TARGET SOURCE EXPECTED
check_pseudocode() {
    local name="$1" target="$2" source="$3" expected="$4"
    local temp_file actual
    temp_file=$(mktemp)
    printf '%s\n' "$source" > "$temp_file"
    actual="$("$SOVA" --pseudocode "$target" "$temp_file" 2>&1)"
    rm -f "$temp_file"

    if [[ "$actual" == "$expected" ]]; then
        echo "[PASS] $name"
        PASS=$((PASS + 1))
    else
        echo "[FAIL] $name"
        diff <(printf '%s\n' "$expected") <(printf '%s\n' "$actual") | sed 's/^/    /'
        FAIL=$((FAIL + 1))
    fi
}

